#ifndef ROBOT_TYPES_H
#define ROBOT_TYPES_H

/*
 * ============================================================
 *  RobotTypes.h
 * ============================================================
 *
 *  这个文件专门定义机械臂需要使用的数据结构。
 *
 *  为什么要单独建立这个文件？
 *
 *  因为以后任务越来越复杂：
 *
 *      摇杆
 *        ↓
 *      舵机角度
 *        ↓
 *      XYZ坐标
 *        ↓
 *      轨迹点
 *
 *  我们需要一种统一的数据格式来保存这些信息。
 *
 * ============================================================
 */


/*
 * ------------------------------------------------------------
 * ServoAngles
 * ------------------------------------------------------------
 *
 * 保存四个舵机当前的角度。
 *
 * 我们暂时把四个舵机定义为：
 *
 * base      = 底座
 * shoulder  = 肩部
 * elbow     = 肘部
 * gripper   = 爪子
 *
 * 注意：
 * 这里的名字只是我们软件中的名字。
 * 如果你们实际机械臂的舵机对应关系不同，
 * 后面只需要修改定义，不影响整体架构。
 * ------------------------------------------------------------
 */
struct ServoAngles
{
    int base;
    int shoulder;
    int elbow;
    int gripper;
};


/*
 * ------------------------------------------------------------
 * JoystickState
 * ------------------------------------------------------------
 *
 * 保存摇杆当前状态。
 *
 * x、y：
 *     原始的模拟量读数。
 *     Arduino UNO 的 analogRead() 范围通常是 0~1023。
 *
 * xActive：
 *     X方向有没有明显移动。
 *
 * yActive：
 *     Y方向有没有明显移动。
 *
 * ------------------------------------------------------------
 */
struct JoystickState
{
    int x;
    int y;

    bool xActive;
    bool yActive;
};


/*
 * ------------------------------------------------------------
 * RobotPose
 * ------------------------------------------------------------
 *
 * 这是给后面的"运动学"和"轨迹规划"准备的。
 *
 * position：
 *     机械臂末端在空间中的位置。
 *
 * base / shoulder / elbow：
 *     机械臂三个关节的角度。
 *
 * gripper：
 *     爪子的角度。
 *
 * 以后任务五的五点示教就可以保存：
 *
 *     RobotPose point1;
 *     RobotPose point2;
 *     ...
 *
 * ------------------------------------------------------------
 */
struct RobotPose
{
    float x;
    float y;
    float z;

    float base;
    float shoulder;
    float elbow;

    float gripper;
};

#endif // ROBOT_TYPES_H
