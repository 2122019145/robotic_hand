#ifndef CONFIG_H
#define CONFIG_H

/*
 * ============================================================
 *  Config.h
 * ============================================================
 *
 *  所有"容易改变的参数"集中放在这里。
 *
 *  好处：
 *
 *  如果以后发现：
 *
 *      底座舵机接到了 D8
 *      肩部舵机接到了 D9
 *
 *  不需要到处寻找数字8、9。
 *
 *  只需要修改这里。
 *
 * ============================================================
 */


/*
 * ============================================================
 * 一、舵机引脚
 * ============================================================
 *
 * 这里暂时按照我们之前讨论的方案：
 *
 * Base      → D8
 * Shoulder  → D9
 * Elbow     → D10
 * Gripper   → D11
 *
 * 如果你的实际接线不同，只修改这里。
 *
 * ============================================================
 */

#define SERVO_BASE_PIN       8
#define SERVO_SHOULDER_PIN  9
#define SERVO_ELBOW_PIN     10
#define SERVO_GRIPPER_PIN   11


/*
 * ============================================================
 * 二、摇杆引脚
 * ============================================================
 *
 * 常见 Arduino 摇杆模块：
 *
 * X → A0
 * Y → A1
 *
 * 如果你的摇杆板实际接线不同，
 * 后面根据实物修改。
 * ============================================================
 */

#define JOYSTICK_X_PIN A0
#define JOYSTICK_Y_PIN A1


/*
 * ============================================================
 * 三、机械臂初始位置
 * ============================================================
 *
 * 这里暂时全部设置为90°。
 *
 * 注意：
 *
 * 90°只是"程序上的暂定值"。
 *
 * 等你拿到实际机械臂以后，
 * 我们需要进行机械零位校准。
 * ============================================================
 */

#define BASE_HOME      90
#define SHOULDER_HOME  90
#define ELBOW_HOME     90
#define GRIPPER_HOME   90


/*
 * ============================================================
 * 四、舵机安全角度范围
 * ============================================================
 *
 * Arduino Servo 库通常允许：
 *
 *     0° ~ 180°
 *
 * 但是机械结构不一定允许这么大的范围。
 *
 * 所以程序必须设置软件限位。
 *
 * 例如：
 *
 *     Base只能20°~160°
 *
 * 那么程序就不能让它跑到10°。
 *
 * 目前先使用0~180，
 * 后面拿到实物以后再校准。
 * ============================================================
 */

#define BASE_MIN       0
#define BASE_MAX     180

#define SHOULDER_MIN   0
#define SHOULDER_MAX 180

#define ELBOW_MIN      0
#define ELBOW_MAX    180

#define GRIPPER_MIN    0
#define GRIPPER_MAX  180


/*
 * ============================================================
 * 五、摇杆死区
 * ============================================================
 *
 * 摇杆即使你完全不碰，
 * analogRead()也可能不是一个完全固定的数。
 *
 * 例如：
 *
 *     512
 *     509
 *     515
 *     511
 *
 * 如果没有"死区"，
 * 机械臂可能会自己轻微运动。
 *
 * 所以我们规定：
 *
 *     距离中心值小于一定范围
 *     → 当作没有移动
 *
 * ============================================================
 */

#define JOYSTICK_DEADZONE 60


/*
 * ============================================================
 * 六、摇杆控制速度
 * ============================================================
 *
 * 这个参数后面用于：
 *
 *     摇杆移动多少
 *     → 舵机角度改变多少
 *
 * 数字越大：
 *
 *     机械臂移动越快
 *
 * ============================================================
 */

#define JOYSTICK_SPEED 1


/*
 * ============================================================
 * 七、串口波特率
 * ============================================================
 *
 * 电脑和Arduino通过USB通信时使用。
 *
 * 115200 是比较常用的高速串口速度。
 * ============================================================
 */

#define SERIAL_BAUDRATE 115200

#endif // CONFIG_H
