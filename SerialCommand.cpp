#include "SerialCommand.h"


/*
 * ============================================================
 *  begin()
 * ============================================================
 *
 *  启动Arduino串口。
 *
 * ============================================================
 */

void SerialCommand::begin(long baudrate)
{
    Serial.begin(baudrate);

    lastCommand = '\0';
}


/*
 * ============================================================
 *  available()
 * ============================================================
 *
 *  Serial.available()
 *
 *  会告诉我们：
 *
 *      "串口缓冲区里面有没有数据。"
 *
 * ============================================================
 */

bool SerialCommand::available()
{
    return Serial.available() > 0;
}


/*
 * ============================================================
 *  read()
 * ============================================================
 *
 *  从串口读取一个字符。
 *
 * ============================================================
 */

char SerialCommand::read()
{
    /*
     * Serial.read()
     *
     * 读取一个字符。
     */
    lastCommand = Serial.read();

    return lastCommand;
}
